// The profile README: designed images in dark/light pairs, joined by real links and plain text.
import { LINKS, STATEMENT, POSTERS, STACK_ROWS, skillIconsUrl, CALLSHEET } from "./content.mjs";
import { renderSlate } from "./render/slate.mjs";
import { renderStats } from "./render/stats.mjs";
import { renderReceipts } from "./render/receipts.mjs";
import { renderCallsheet } from "./render/callsheet.mjs";
import { renderButton } from "./render/button.mjs";
import { esc } from "./render/svg.mjs";
import { dailyName } from "./data/projects.mjs";

/** The call-sheet buttons (R6): asset name, label, link and variant. */
export const BUTTONS = [
  { name: "hire", label: CALLSHEET.links[0].label, href: CALLSHEET.links[0].href, variant: "primary" },
  { name: "site", label: CALLSHEET.links[1].label, href: CALLSHEET.links[1].href, variant: "secondary" },
  { name: "linkedin", label: CALLSHEET.links[2].label, href: CALLSHEET.links[2].href, variant: "secondary" },
];

export const DAILIES_START = "<!-- dailies:start -->";
export const DAILIES_END = "<!-- dailies:end -->";

/** An SVG's <title>, already escaped: the image's alt text is exactly what the image says. */
const titleOf = (svg) => svg.match(/<title[^>]*>([^<]*)<\/title>/)[1];

/**
 * A dark/light pair. `align="top"` sits the image at the top of its line box, so no
 * descender gap opens under it (that is what lets the slate and stats stack seamlessly).
 */
const picture = (name, alt, { ext = "svg", width } = {}) =>
  `<picture><source media="(prefers-color-scheme: dark)" srcset="assets/${name}-dark.${ext}">` +
  `<img src="assets/${name}-light.${ext}" alt="${alt}"${width ? ` width="${width}"` : ""} align="top"></picture>`;

/** GitHub links a bare image to its raw file; a real link sends the click somewhere useful. */
const linked = (href, html) => `<a href="${href}">${html}</a>`;

/** The cards are drawn 830 px wide; a share of that keeps a small image in proportion to them. */
const CARD_PX = 830;
const shareOfCard = (px) => `${+((px / CARD_PX) * 100).toFixed(1)}%`;

const posterAlt = (p) => esc(`${p.name}. ${p.kicker.replace(" · ", ", ").toLowerCase()}. ${p.line}`);

/**
 * Three linked posters in one row. A paragraph, not a table: GitHub draws borders around
 * table cells, the mock has none. Percentage widths keep the row whole on a phone.
 */
function posters() {
  return `<p>${POSTERS.map(
    (p) =>
      `<a href="${LINKS.caseFile(p.slug)}"><img src="assets/poster-${p.slug}.png" alt="${posterAlt(p)}" width="32.2%"></a>`
  ).join(" ")}</p>`;
}

/** The text-link line under the dailies strip, between the R3 markers. */
export function dailiesLine(dailies) {
  const links = dailies.map((d) => `<a href="${LINKS.caseFile(d.slug)}">${esc(dailyName(d.name))}</a>`).join(" · ");
  return `${DAILIES_START}\n${links}\n${DAILIES_END}`;
}

function dailiesAlt(dailies) {
  const names = dailies.map((d) => dailyName(d.name)).join(", ");
  return esc(names ? `Dailies: a film strip of more projects, ${names}.` : "Dailies: a film strip of more projects.");
}

/**
 * skillicons.dev draws n icons on a 300-unit stride (256 icon + 44 gap). Sizing each row as a
 * share of the 830 px card width keeps every row's icons the same size at any page width.
 */
const ICON_PX = 40;
const iconRowWidth = (n) => shareOfCard(((n * 300 - 44) * ICON_PX) / 256);

const stackRows = () =>
  STACK_ROWS.map((r) => {
    const icons = r.icons.split(",");
    const alt = esc(`${r.label}: ${icons.join(", ")}`);
    return `<p><b>${esc(r.label)}</b><br><img src="${skillIconsUrl(r.icons)}" alt="${alt}" width="${iconRowWidth(icons.length)}"></p>`;
  }).join("\n\n");

/** Percentage widths, like the posters: the row keeps its 830 px proportions and shrinks on a phone. */
const buttonWidth = (b) => shareOfCard(Number(renderButton("dark", b).match(/\bwidth="(\d+)"/)[1]));

const buttons = () =>
  `<p>${BUTTONS.map((b) =>
    linked(b.href, picture(`button-${b.name}`, esc(b.label), { width: buttonWidth(b) }))
  ).join("&nbsp;&nbsp;")}</p>`;

/**
 * dailies: [{ slug, name }] for the film strip's links.
 * stats: { total, activeDays, longestStreak, shipped } as drawn in stats.svg (for its alt text).
 */
export function renderReadme({ dailies, stats }) {
  return [
    "<!-- Generated by scripts/build.mjs. Edit the scripts, not this file. -->",
    // One line box, split by <br>: with align="top" on both, the link adds no gap between them.
    linked(LINKS.site, picture("slate", titleOf(renderSlate("dark")))) +
      "<br>" +
      linked(LINKS.site, picture("stats", titleOf(renderStats("dark", stats)))),
    STATEMENT,
    "## Now showing",
    posters(),
    "## Dailies",
    linked(LINKS.projects, picture("dailies", dailiesAlt(dailies), { ext: "png", width: CARD_PX })),
    dailiesLine(dailies),
    "## Receipts",
    picture("receipts", titleOf(renderReceipts("dark"))),
    "## On every set",
    stackRows(),
    "## Call sheet",
    linked(LINKS.hire, picture("callsheet", titleOf(renderCallsheet("dark")))),
    buttons(),
  ].join("\n\n") + "\n";
}
